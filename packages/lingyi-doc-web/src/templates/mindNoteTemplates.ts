import type { MindNode, MindNoteJSON } from '@lingyi-doc/core';
import { createEmptyMindNote, genMindNodeId } from '@lingyi-doc/core';

type NodeInput = string | [string, NodeInput[]];

function buildNode(input: NodeInput): MindNode {
  if (typeof input === 'string') {
    return { id: genMindNodeId(), text: input, children: [] };
  }
  const [text, children] = input;
  return {
    id: genMindNodeId(),
    text,
    children: children.map(buildNode),
  };
}

function buildMindNote(title: string, rootText: string, children: NodeInput[]): MindNoteJSON {
  const json = createEmptyMindNote('', title);
  json.root.text = rootText;
  json.root.children = children.map(buildNode);
  return json;
}

